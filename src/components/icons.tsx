import type { SVGProps, ReactElement } from "react";

export interface LucideProps extends SVGProps<SVGSVGElement> {
  size?: number | string;
  strokeWidth?: number | string;
  className?: string;
}

function createIcon(
  name: string,
  paths: (props: LucideProps) => ReactElement,
) {
  const Icon = ({
    size = 24,
    strokeWidth = 2,
    className = "",
    ...props
  }: LucideProps) => {
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={`shrink-0 ${className}`}
        aria-hidden="true"
        data-lucide={name}
        {...props}
      >
        {paths(props)}
      </svg>
    );
  };
  Icon.displayName = name;
  return Icon;
}

